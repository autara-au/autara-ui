#!/usr/bin/env node
/**
 * AUTM-1870: writes src/lib/vehicle-make-logos.ts, the make marks the vehicle
 * picker draws, from a Simple Icons package on disk. Simple Icons is not a
 * dependency: its 3,400 icons would ship to every consumer for 23 we use.
 *
 *   npm pack simple-icons && tar -xzf simple-icons-*.tgz
 *   node scripts/gen-vehicle-make-logos.mjs path/to/package
 *
 * Only the path data is copied, monochrome, so the consumer tints it with a
 * token (currentColor). A make Simple Icons does not carry has no entry and
 * the picker draws its monogram instead.
 */
import { readFileSync, writeFileSync } from 'node:fs'
import { join } from 'node:path'

const pkg = process.argv[2]
if (!pkg) throw new Error('pass the simple-icons package directory')
const { version } = JSON.parse(readFileSync(join(pkg, 'package.json'), 'utf8'))

/* Our make slug (vehicleSlug of the catalog name) -> the Simple Icons slug. */
const MAKES = {
    audi: 'audi', bmw: 'bmw', ford: 'ford', honda: 'honda', hyundai: 'hyundai', jeep: 'jeep', kia: 'kia',
    mazda: 'mazda', mg: 'mg', mini: 'mini', mitsubishi: 'mitsubishi', nissan: 'nissan', peugeot: 'peugeot',
    porsche: 'porsche', ram: 'ram', renault: 'renault', skoda: 'skoda', subaru: 'subaru', suzuki: 'suzuki',
    tesla: 'tesla', toyota: 'toyota', volkswagen: 'volkswagen', volvo: 'volvo',
}

const entries = Object.entries(MAKES).map(([ours, theirs]) => {
    const svg = readFileSync(join(pkg, 'icons', `${theirs}.svg`), 'utf8')
    if (!svg.includes('viewBox="0 0 24 24"')) throw new Error(`${theirs}: not a 24 x 24 icon`)
    const paths = [...svg.matchAll(/<path d="([^"]+)"/g)].map((m) => m[1])
    if (paths.length !== 1) throw new Error(`${theirs}: expected one path, found ${paths.length}`)
    return `    '${ours}': '${paths[0]}',`
})

writeFileSync(
    'src/lib/vehicle-make-logos.ts',
    `/**
 * AUTM-1870: the make marks VehiclePicker draws (Don approved real make logos,
 * 2026-10-14), from Simple Icons ${version}. GENERATED by
 * scripts/gen-vehicle-make-logos.mjs: do not edit by hand.
 *
 * Simple Icons' data is CC0-1.0; the marks themselves are their makers'
 * trademarks, shown only to name the customer's own car. Each is one path on
 * a 24 x 24 box, drawn in currentColor so a token tints it in both themes.
 * Keys are the catalog make's vehicleSlug. A make missing here (BYD, Isuzu,
 * Holden, GWM, Chery and others Simple Icons does not carry) draws a monogram.
 */
export const VEHICLE_MAKE_LOGO_SOURCE = 'simple-icons@${version}'

export const VEHICLE_MAKE_LOGO_PATHS: Record<string, string> = {
${entries.join('\n')}
}
`
)
console.log(`wrote ${entries.length} marks from simple-icons@${version}`)
